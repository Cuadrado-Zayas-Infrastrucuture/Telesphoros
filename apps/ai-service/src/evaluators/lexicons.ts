const familyIndex = new Map<string, string>();
for (const [family, forms] of Object.entries(DIRECTIVE_FAMILIES)) for (const form of forms) familyIndex.set(form, family);
export const familyOf = (token: string): string | undefined => familyIndex.get(token);

