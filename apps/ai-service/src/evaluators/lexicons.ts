  lower: ['lower', 'lowers', 'lowered', 'lowering'],
  raise: ['raise', 'raises', 'raised', 'raising'],
  higher: ['higher', 'greater', 'more', 'elevated', 'extra'],
  less: ['less', 'fewer', 'smaller', 'slower'],
