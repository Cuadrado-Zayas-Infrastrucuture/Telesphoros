-- Core tables: patients, reports, recommendations.
-- Design rules:
--   * Public ids are UUIDs (gen_random_uuid(), built into PostgreSQL 13+), matching the Phase 2 DTOs.
--   * Every row has an owner_id; every foreign key is COMPOSITE (id, owner_id), so a child row can
--     never point at another owner's parent, even if application code or RLS were bypassed.
--   * Soft delete (deleted_at). Hard deletes are for a future retention job, not the application.
--   * Every foreign key states ON DELETE explicitly: RESTRICT everywhere (clinical history is not
--     silently cascaded away).
--   * `seq` gives a stable creation order for pagination (timestamps can tie).

CREATE FUNCTION set_updated_at() RETURNS trigger LANGUAGE plpgsql AS $$
BEGIN
  -- Respect an explicit value from the application; bump it only if the writer did not.
  IF NEW.updated_at IS NOT DISTINCT FROM OLD.updated_at THEN
    NEW.updated_at := now();
  END IF;
  RETURN NEW;
END
$$;

CREATE TABLE patients (
  seq        bigint GENERATED ALWAYS AS IDENTITY NOT NULL,
  id         uuid PRIMARY KEY DEFAULT gen_random_uuid(),
  owner_id   text NOT NULL,
  -- Patients are identified ONLY by a synthetic label. No name, date of birth or real identifier.
  label      text NOT NULL,
  created_at timestamptz NOT NULL DEFAULT now(),
  updated_at timestamptz NOT NULL DEFAULT now(),
  deleted_at timestamptz,
  CONSTRAINT patients_owner_id_len CHECK (length(owner_id) BETWEEN 1 AND 128),
  CONSTRAINT patients_label_format CHECK (length(label) BETWEEN 1 AND 40 AND label ~ '^[A-Za-z0-9-]+$'),
  -- Target of the composite foreign keys below.
  CONSTRAINT patients_id_owner_uq UNIQUE (id, owner_id)
);
-- One live label per owner, ignoring case. A soft-deleted patient frees its label.
CREATE UNIQUE INDEX patients_owner_label_uq ON patients (owner_id, lower(label)) WHERE deleted_at IS NULL;
CREATE INDEX patients_owner_seq_idx ON patients (owner_id, seq) WHERE deleted_at IS NULL;
CREATE TRIGGER patients_set_updated_at BEFORE UPDATE ON patients FOR EACH ROW EXECUTE FUNCTION set_updated_at();

CREATE TABLE reports (
  seq               bigint GENERATED ALWAYS AS IDENTITY NOT NULL,
  id                uuid PRIMARY KEY DEFAULT gen_random_uuid(),
  owner_id          text NOT NULL,
  patient_id        uuid NOT NULL,
  type              text NOT NULL,
  -- The name the user supplied. The object key in storage is generated by the server, never from this.
  original_filename text NOT NULL,
  size_bytes        bigint NOT NULL,
  status            text NOT NULL DEFAULT 'received',
  -- Filled in by the upload flow (object storage holds the bytes; the database never does).
  content_type      text,
  sha256            text,
  storage_key       text,
  uploaded_at       timestamptz,
  created_at        timestamptz NOT NULL DEFAULT now(),
  updated_at        timestamptz NOT NULL DEFAULT now(),
  deleted_at        timestamptz,
  CONSTRAINT reports_owner_id_len CHECK (length(owner_id) BETWEEN 1 AND 128),
  CONSTRAINT reports_type_valid CHECK (type IN ('vcf', 'structured')),
  CONSTRAINT reports_filename_format CHECK (
    length(original_filename) BETWEEN 1 AND 100 AND original_filename ~ '^[A-Za-z0-9._-]+$'
  ),
  CONSTRAINT reports_size_range CHECK (size_bytes BETWEEN 1 AND 10485760),
  CONSTRAINT reports_status_valid CHECK (status IN ('received', 'processing', 'processed', 'failed')),
  CONSTRAINT reports_sha256_format CHECK (sha256 IS NULL OR sha256 ~ '^[0-9a-f]{64}$'),
  CONSTRAINT reports_upload_consistent CHECK (
    uploaded_at IS NULL OR (storage_key IS NOT NULL AND sha256 IS NOT NULL AND content_type IS NOT NULL)
  ),
  CONSTRAINT reports_id_owner_uq UNIQUE (id, owner_id),
  CONSTRAINT reports_patient_fk FOREIGN KEY (patient_id, owner_id)
    REFERENCES patients (id, owner_id) ON DELETE RESTRICT
);
-- The same object can never be registered for two reports.
CREATE UNIQUE INDEX reports_storage_key_uq ON reports (storage_key) WHERE storage_key IS NOT NULL;
CREATE INDEX reports_owner_seq_idx ON reports (owner_id, seq) WHERE deleted_at IS NULL;
CREATE INDEX reports_owner_patient_idx ON reports (owner_id, patient_id) WHERE deleted_at IS NULL;
-- Lets the RESTRICT check on patients (and the delete guard below) find child rows without a scan.
CREATE INDEX reports_patient_idx ON reports (patient_id);
CREATE TRIGGER reports_set_updated_at BEFORE UPDATE ON reports FOR EACH ROW EXECUTE FUNCTION set_updated_at();

CREATE TABLE recommendations (
  seq               bigint GENERATED ALWAYS AS IDENTITY NOT NULL,
  id                uuid PRIMARY KEY DEFAULT gen_random_uuid(),
  owner_id          text NOT NULL,
  patient_id        uuid NOT NULL,
  report_id         uuid NOT NULL,
  gene              text NOT NULL,
  drug              text NOT NULL,
  phenotype         text NOT NULL,
  summary           text NOT NULL,
  strength          text NOT NULL,
  guideline_version text NOT NULL,
  created_at        timestamptz NOT NULL DEFAULT now(),
  updated_at        timestamptz NOT NULL DEFAULT now(),
  deleted_at        timestamptz,
  CONSTRAINT recommendations_owner_id_len CHECK (length(owner_id) BETWEEN 1 AND 128),
  CONSTRAINT recommendations_strength_valid CHECK (strength IN ('Strong', 'Moderate', 'Optional', 'No recommendation')),
  CONSTRAINT recommendations_patient_fk FOREIGN KEY (patient_id, owner_id)
    REFERENCES patients (id, owner_id) ON DELETE RESTRICT,
  CONSTRAINT recommendations_report_fk FOREIGN KEY (report_id, owner_id)
    REFERENCES reports (id, owner_id) ON DELETE RESTRICT
);
CREATE INDEX recommendations_owner_seq_idx ON recommendations (owner_id, seq) WHERE deleted_at IS NULL;
CREATE INDEX recommendations_owner_patient_idx ON recommendations (owner_id, patient_id) WHERE deleted_at IS NULL;
CREATE INDEX recommendations_owner_report_idx ON recommendations (owner_id, report_id) WHERE deleted_at IS NULL;
CREATE INDEX recommendations_patient_idx ON recommendations (patient_id);
CREATE INDEX recommendations_report_idx ON recommendations (report_id);
CREATE TRIGGER recommendations_set_updated_at BEFORE UPDATE ON recommendations FOR EACH ROW EXECUTE FUNCTION set_updated_at();

-- Soft delete bypasses foreign keys, so enforce the same RESTRICT rule for it explicitly.
CREATE FUNCTION block_patient_soft_delete() RETURNS trigger LANGUAGE plpgsql AS $$
BEGIN
  IF EXISTS (SELECT 1 FROM reports WHERE patient_id = OLD.id AND deleted_at IS NULL) THEN
    RAISE EXCEPTION 'patient still has live reports' USING ERRCODE = 'foreign_key_violation';
  END IF;
  RETURN NEW;
END
$$;
CREATE TRIGGER patients_block_soft_delete BEFORE UPDATE OF deleted_at ON patients
  FOR EACH ROW WHEN (OLD.deleted_at IS NULL AND NEW.deleted_at IS NOT NULL)
  EXECUTE FUNCTION block_patient_soft_delete();

CREATE FUNCTION block_report_soft_delete() RETURNS trigger LANGUAGE plpgsql AS $$
BEGIN
  IF EXISTS (SELECT 1 FROM recommendations WHERE report_id = OLD.id AND deleted_at IS NULL) THEN
    RAISE EXCEPTION 'report still has live recommendations' USING ERRCODE = 'foreign_key_violation';
  END IF;
  RETURN NEW;
END
$$;
CREATE TRIGGER reports_block_soft_delete BEFORE UPDATE OF deleted_at ON reports
  FOR EACH ROW WHEN (OLD.deleted_at IS NULL AND NEW.deleted_at IS NOT NULL)
  EXECUTE FUNCTION block_report_soft_delete();
