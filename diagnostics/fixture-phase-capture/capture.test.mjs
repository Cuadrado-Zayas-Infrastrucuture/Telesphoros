import assert from 'node:assert/strict';
import { spawn, spawnSync } from 'node:child_process';
import { mkdtempSync, readFileSync, writeFileSync, rmSync, mkdirSync } from 'node:fs';
import { tmpdir } from 'node:os';
import { join } from 'node:path';
import { fileURLToPath } from 'node:url';
import test from 'node:test';
import { root, baseline, sourceSnapshot, verifySelection, parseTests, verifyCapture, supervise, profileScript } from './capture.mjs';
const expected = JSON.parse(readFileSync(new URL('./expected-files.json', import.meta.url)));
const actor = 'test/db/system-actor.pg-spec.ts';
function fixture(t) {
  const dir = mkdtempSync(join(tmpdir(), 'fixture-capture-control-'));
  // Disposable newly-created synthetic fixtures only; all can be regenerated by this test.
  t.after(() => rmSync(dir, { recursive: true, force: true }));
  return dir;
}
function log(failed = false) {
  return expected.active.map(file => `${failed && file === actor ? 'FAIL' : 'PASS'} ${file}`).join('\n') + '\n'
    + (failed ? 'FAIL ' + actor + '\n' : '')
    + `Test Suites: ${failed ? '1 failed, ' : ''}11 skipped, ${failed ? 158 : 159} passed, 159 of 170 total\n`
    + `Tests: ${failed ? '11 failed, ' : ''}253 skipped, ${failed ? 2221 : 2232} passed, 2485 total\nTime: 493 s\n`;
}
function observed(t, failed = false) {
  const dir = fixture(t);
  const setup = expected.active.map(file => ({ event: 'suite-open', file }));
  setup.push({ event: 'fixture-start', file: actor, id: 1 }, { event: 'operation-start', file: actor, id: 1, phase: 'role-lock' });
  if (!failed) setup.push({ event: 'fixture-end', file: actor, id: 1, ok: true });
  for (const [name, rows] of [['setup.jsonl', setup], ['preload.jsonl', [{ event: 'config', testTimeout: 5000, maxWorkers: 1, observerCount: 1 }]],
    ['pg-watch.jsonl', [{ event: 'connected' }, { event: 'sample' }, { event: 'stopped' }]]]) writeFileSync(join(dir, name), rows.map(JSON.stringify).join('\n') + '\n');
  return dir;
}

test('the workload stays complete and both diagnostic selections match the original file order', () => {
  const files = expected.selected.map(file => join(root, 'apps/backend', file));
  assert.equal(verifySelection(files, [...files]).selectedFiles, 170);
  assert.throws(() => verifySelection(files, files.slice(1)));
  const reordered = [...files]; [reordered[0], reordered[1]] = [reordered[1], reordered[0]];
  assert.throws(() => verifySelection(reordered, reordered));
  assert.equal(profileScript, 'set -o pipefail\npnpm --filter @telesphoros/backend test 2>&1 | tee tier1.log\n! grep -F "[jest] NOT RUNNING" tier1.log\n');
});

test('full original failure is valid diagnostic evidence without becoming a product pass', t => {
  const dir = observed(t, true), result = verifyCapture(dir, log(true), 1);
  assert.equal(result.captureComplete, true); assert.equal(result.productPassed, false);
  assert.equal(result.tests.files.length, 159); assert.equal(result.tests.counts.tests.failed, 11);
  assert.equal(result.completedFixtures, 0); // A timed-out actor need not have completed to retain useful starts.
  assert.throws(() => verifyCapture(dir, log(true), 0));
});

test('missing fixture/monitor records, altered deadlines and incomplete logs cannot appear green', t => {
  const dir = observed(t);
  assert.equal(verifyCapture(dir, log(), 0).productPassed, true);
  assert.equal(parseTests(log().replace('2232 passed', '2231 passed')).complete, false);
  assert.equal(parseTests(log().replace(`PASS ${expected.active[0]}\n`, '')).complete, false);
  assert.throws(() => parseTests(log() + 'FAIL ' + expected.active[0] + '\n'));
  writeFileSync(join(dir, 'preload.jsonl'), JSON.stringify({ event: 'config', testTimeout: 30000, maxWorkers: 1, observerCount: 1 }) + '\n');
  assert.throws(() => verifyCapture(dir, log(), 0));
  writeFileSync(join(dir, 'preload.jsonl'), JSON.stringify({ event: 'config', testTimeout: 5000, maxWorkers: 1, observerCount: 1 }) + '\n');
  writeFileSync(join(dir, 'pg-watch.jsonl'), '{"event":"connected"}\n{"event":"sample"}\n');
  assert.throws(() => verifyCapture(dir, log(), 0));
});

test('a recording failure rejects capture while retaining native producer truth', t => {
  const dir = observed(t, true);
  writeFileSync(join(dir, 'capture-errors.jsonl'), '{"event":"capture-error"}\n');
  assert.throws(() => verifyCapture(dir, log(true), 1));
  assert.equal(parseTests(log(true)).counts.tests.failed, 11);
});

test('bounded partial evidence remains uploadable even when final verification fails', t => {
  const temp = fixture(t), dir = join(temp, 'fixture-phase-capture'), output = join(temp, 'github.output');
  mkdirSync(dir); writeFileSync(join(dir, 'setup.jsonl'), '{"event":"fixture-start"}\n');
  const child = spawnSync(process.execPath, [fileURLToPath(new URL('./capture.mjs', import.meta.url)), 'finalize'], {
    env: { ...process.env, RUNNER_TEMP: temp, FIXTURE_CAPTURE_DIR: dir, GITHUB_OUTPUT: output }, encoding: 'utf8' });
  assert.equal(child.status, 1); assert.equal(readFileSync(output, 'utf8'), 'bounded=true\n');
});

test('real child supervision preserves a failed producer and stops a healthy monitor', async () => {
  const child = spawn(process.execPath, ['-e', "process.on('SIGTERM',()=>process.exit(0));console.log('ready');setInterval(()=>{},1000)"], { stdio: ['ignore', 'pipe', 'ignore'] });
  const ready = () => new Promise(done => child.stdout.once('data', done));
  const result = await supervise(async () => 1, child, ready);
  assert.equal(result.native, 1); assert.equal(result.premature, false); assert.deepEqual(result.monitor, { code: 0, signal: null });
});

test('a monitor that dies during production cannot qualify as a healthy capture', async () => {
  const child = spawn(process.execPath, ['-e', "console.log('ready');setTimeout(()=>process.exit(3),30)"], { stdio: ['ignore', 'pipe', 'ignore'] });
  const ready = () => new Promise(done => child.stdout.once('data', done));
  const result = await supervise(async () => { await new Promise(done => setTimeout(done, 80)); return 0; }, child, ready);
  assert.equal(result.native, 0); assert.equal(result.premature, true); assert.equal(result.monitor.code, 3);
});

test('cleanup does not replace an exact producer rejection', async () => {
  const failure = new Error('synthetic producer failure');
  const child = spawn(process.execPath, ['-e', "process.on('SIGTERM',()=>process.exit(0));console.log('ready');setInterval(()=>{},1000)"], { stdio: ['ignore', 'pipe', 'ignore'] });
  await assert.rejects(supervise(async () => { throw failure; }, child, () => new Promise(done => child.stdout.once('data', done))), error => error === failure);
});

